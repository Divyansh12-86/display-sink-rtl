#!/usr/bin/env python3
"""
scripts/golden/generate_gamma_luts.py
Generates 256-entry exact Gamma 2.2 and sRGB lookup functions for synthesizable RTL ROMs.
Compatible with all synthesis tools including Yosys, QuestaSim, and Verilator.
"""

import numpy as np

def generate_tables():
    x = np.arange(256) / 255.0
    
    # Gamma 2.2 Power Curve: Out = round(255 * (In / 255) ^ 2.2)
    g22 = np.round(255.0 * (x ** 2.2)).astype(int)
    
    # sRGB EOTF Curve (Standard IEC 61966-2-1)
    # Linear slope 1/12.92 below 0.04045, exponent 2.4 above
    srgb = np.round(255.0 * np.where(x <= 0.04045, x / 12.92, ((x + 0.055) / 1.055) ** 2.4)).astype(int)
    
    # Ensure end-points are exact
    g22[0] = 0; g22[255] = 255
    srgb[0] = 0; srgb[255] = 255
    
    return g22, srgb

def emit_sv_functions():
    g22, srgb = generate_tables()
    
    lines = []
    lines.append("// Auto-generated by scripts/golden/generate_gamma_luts.py")
    lines.append("// Exact 256-entry Gamma 2.2 and sRGB EOTF Tables")
    lines.append("")
    lines.append("function automatic logic [7:0] lut_gamma22(input logic [7:0] val);")
    lines.append("  begin")
    lines.append("    case (val)")
    for i in range(256):
        lines.append(f"      8'd{i}: lut_gamma22 = 8'd{g22[i]};")
    lines.append("    endcase")
    lines.append("  end")
    lines.append("endfunction")
    lines.append("")
    lines.append("function automatic logic [7:0] lut_srgb(input logic [7:0] val);")
    lines.append("  begin")
    lines.append("    case (val)")
    for i in range(256):
        lines.append(f"      8'd{i}: lut_srgb = 8'd{srgb[i]};")
    lines.append("    endcase")
    lines.append("  end")
    lines.append("endfunction")
    lines.append("")
    
    return "\n".join(lines)

if __name__ == "__main__":
    content = emit_sv_functions()
    with open("rtl/color/gamma_rom_data.vh", "w") as f:
        f.write(content)
    print("[SUCCESS] Generated rtl/color/gamma_rom_data.vh with 256-entry exact Gamma 2.2 and sRGB functions.")
